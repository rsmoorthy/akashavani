#pragma once

#include <cstddef>
#include <cstdint>

namespace akashavani {

// Davis Instruments ISS frequency-hopping table for North America.
//
// The values are the three RFM69/SX1231 REG_FRFMSB/MID/LSB bytes copied from
// the validated prototype (prototype/lib2/DavisRFM69/DavisRFM69.h). They cover
// 902.38 MHz to 927.47 MHz, inside the US 902-928 MHz ISM band. The order is
// the transmitter's hop order, not a monotonic frequency sweep.
//
// Do not reorder or "round" these values: the receiver and transmitter must use
// the identical table or they will never align.
constexpr size_t kDavisChannelCount = 51;

struct DavisChannelRegisters {
  uint8_t msb;
  uint8_t mid;
  uint8_t lsb;
};

constexpr DavisChannelRegisters kDavisChannelTable[kDavisChannelCount] = {
    {0xE3, 0xDA, 0x7C}, {0xE1, 0x98, 0x71}, {0xE3, 0xFA, 0x92},
    {0xE6, 0xBD, 0x01}, {0xE4, 0xBB, 0x4D}, {0xE2, 0x99, 0x56},
    {0xE7, 0x7D, 0xBC}, {0xE5, 0x9C, 0x0E}, {0xE3, 0x39, 0xE6},
    {0xE6, 0x1C, 0x81}, {0xE4, 0x5A, 0xE8}, {0xE1, 0xF8, 0xD6},
    {0xE5, 0x3B, 0xBF}, {0xE7, 0x1D, 0x5F}, {0xE3, 0x9A, 0x3C},
    {0xE2, 0x39, 0x00}, {0xE4, 0xFB, 0x77}, {0xE6, 0x5C, 0xB2},
    {0xE2, 0xD9, 0x90}, {0xE7, 0xBD, 0xEE}, {0xE4, 0x3A, 0xD2},
    {0xE1, 0xD8, 0xAA}, {0xE5, 0x5B, 0xCD}, {0xE6, 0xDD, 0x34},
    {0xE3, 0x5A, 0x0A}, {0xE7, 0x9D, 0xD9}, {0xE2, 0x79, 0x41},
    {0xE4, 0x9B, 0x28}, {0xE5, 0xDC, 0x40}, {0xE7, 0x3D, 0x74},
    {0xE1, 0xB8, 0x9C}, {0xE3, 0xBA, 0x60}, {0xE6, 0x7C, 0xC8},
    {0xE4, 0xDB, 0x62}, {0xE2, 0xB9, 0x7A}, {0xE5, 0x7B, 0xE2},
    {0xE7, 0xDE, 0x12}, {0xE6, 0x3C, 0x9D}, {0xE3, 0x19, 0xC9},
    {0xE4, 0x1A, 0xB6}, {0xE5, 0xBC, 0x2B}, {0xE2, 0x18, 0xEB},
    {0xE6, 0xFD, 0x42}, {0xE5, 0x1B, 0xA3}, {0xE3, 0x7A, 0x2E},
    {0xE5, 0xFC, 0x64}, {0xE2, 0x59, 0x16}, {0xE6, 0x9C, 0xEC},
    {0xE2, 0xF9, 0xAC}, {0xE4, 0x7B, 0x0C}, {0xE7, 0x5D, 0x98},
};

// RFM69 synthesizer step: 32 MHz / 2^19.
constexpr float kRfm69FrequencyStepHz = 61.03515625f;

constexpr uint32_t davisChannelRegisterValue(uint8_t channel) {
  const size_t index = channel < kDavisChannelCount ? channel : 0;
  return (static_cast<uint32_t>(kDavisChannelTable[index].msb) << 16) |
         (static_cast<uint32_t>(kDavisChannelTable[index].mid) << 8) |
         kDavisChannelTable[index].lsb;
}

constexpr float davisChannelFrequencyMhz(uint8_t channel) {
  return static_cast<float>(davisChannelRegisterValue(channel)) *
         kRfm69FrequencyStepHz / 1000000.0f;
}

constexpr uint8_t nextDavisChannel(uint8_t channel) {
  return static_cast<uint8_t>((channel + 1) % kDavisChannelCount);
}

constexpr uint8_t previousDavisChannel(uint8_t channel) {
  return static_cast<uint8_t>((channel + kDavisChannelCount - 1) % kDavisChannelCount);
}

}  // namespace akashavani
